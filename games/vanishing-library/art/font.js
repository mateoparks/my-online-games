      h: g('#... #... ###. #..# #..# #..# #..#'),
      i: g('# . # # # # #'),
      j: g('..# ... .## ..# ..# ..# ..# #.# .#.'),
      k: g('#... #... #..# #.#. ##.. #.#. #..#'),
      l: g('##. .#. .#. .#. .#. .#. ..#'),
      m: g('..... ..... ##.#. #.#.# #.#.# #.#.# #...#'),
      n: g('.... .... ###. #..# #..# #..# #..#'),
      o: g('.... .... .##. #..# #..# #..# .##.'),
      p: g('.... .... ###. #..# #..# #..# ###. #... #...'),
      q: g('.... .... .### #..# #..# #..# .### ...# ...#'),
      r: g('... ... #.# ##. #.. #.. #..'),
      s: g('.... .... .### #... .##. ...# ###.'),
      t: g('.#. .#. ### .#. .#. .#. ..#'),
      u: g('.... .... #..# #..# #..# #..# .###'),
      v: g('..... ..... #...# #...# .#.#. .#.#. ..#..'),
      w: g('..... ..... #...# #...# #.#.# #.#.# .#.#.'),
      x: g('.... .... #..# #..# .##. #..# #..#'),
      y: g('.... .... #..# #..# #..# #..# .### ...# .##.'),
      z: g('.... .... #### ...# .##. #... ####'),
      0: g('.###. #...# #..## #.#.# ##..# #...# .###.'),
      1: g('..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.'),
      2: g('.###. #...# ....# ...#. ..#.. .#... #####'),
      3: g('####. ....# ....# .###. ....# ....# ####.'),
      4: g('...#. ..##. .#.#. #..#. ##### ...#. ...#.'),
      5: g('##### #.... ####. ....# ....# #...# .###.'),
      6: g('.###. #.... #.... ####. #...# #...# .###.'),
      7: g('##### ....# ...#. ..#.. .#... .#... .#...'),
